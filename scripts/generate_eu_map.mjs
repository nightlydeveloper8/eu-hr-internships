// Regenerates src/eu-map.js (EU-27 + Switzerland + United Kingdom map paths) from Natural Earth 1:50m via world-atlas (public domain).
// Dev-only, not needed for the daily build:
//   npm install --no-save world-atlas@2 topojson-client d3-geo && node scripts/generate_eu_map.mjs src/eu-map.js
import {readFileSync, writeFileSync} from 'node:fs';
import {feature} from 'topojson-client';
import {geoAzimuthalEqualArea, geoPath, geoCentroid} from 'd3-geo';

const out = process.argv[2];
const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/countries-50m.json', import.meta.url)));
const all = feature(topo, topo.objects.countries).features;

const EU = {AT:'040',BE:'056',BG:'100',HR:'191',CY:'196',CZ:'203',DK:'208',EE:'233',FI:'246',FR:'250',DE:'276',GR:'300',HU:'348',IE:'372',IT:'380',LV:'428',LT:'440',LU:'442',MT:'470',NL:'528',PL:'616',PT:'620',RO:'642',SK:'703',SI:'705',ES:'724',SE:'752',CH:'756',GB:'826'};
const byNum = Object.fromEntries(Object.entries(EU).map(([a, n]) => [n, a]));

// Keep only the European parts of each country (drops overseas territories, Canaries, Azores, Madeira).
const inEurope = ([lon, lat]) => lon > -12 && lon < 45 && lat > 34 && lat < 72;
function europeOnly(f) {
  const g = f.geometry;
  if (!g) return null;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.type === 'MultiPolygon' ? g.coordinates : [];
  const kept = polys.filter(p => inEurope(geoCentroid({type: 'Polygon', coordinates: p})));
  return kept.length ? {...f, geometry: {type: 'MultiPolygon', coordinates: kept}} : null;
}

const eu = all.filter(f => byNum[f.id]).map(europeOnly).filter(Boolean);
const W = 1000, H = 860, PAD = 14;
const projection = geoAzimuthalEqualArea().rotate([-12, -52]).fitExtent([[PAD, PAD], [W - PAD, H - PAD]], {type: 'FeatureCollection', features: eu});
projection.clipExtent([[0, 0], [W, H]]);
const path = geoPath(projection).digits(1);

const countries = {};
for (const f of eu) {
  const code = byNum[f.id];
  const [cx, cy] = projection(geoCentroid(f));
  const [[x0, y0], [x1, y1]] = path.bounds(f);
  countries[code] = {d: path(f), cx: +cx.toFixed(1), cy: +cy.toFixed(1), small: Math.max(x1 - x0, y1 - y0) < 22};
}
// Visual label anchors for countries whose geometric centroid falls awkwardly.
const nudge = {FR: [2, 46.6], SE: [15.5, 62.5], FI: [26, 63], IT: [12.6, 42.8], HR: [16.2, 45.3], DK: [9.2, 56], GR: [22, 39.5], PT: [-8, 39.8]};
for (const [code, ll] of Object.entries(nudge)) { const [x, y] = projection(ll); countries[code].cx = +x.toFixed(1); countries[code].cy = +y.toFixed(1); }

const context = all.filter(f => !byNum[f.id] && f.geometry)
  .map(f => path(f))
  .filter(d => d && d.length > 8);

const js = `// Generated by a build-time script from Natural Earth 1:50m (public domain) via world-atlas.\n// Do not edit by hand. Projection: azimuthal equal-area centred on Europe.\nexport const MAP_VIEWBOX = '0 0 ${W} ${H}';\nexport const EU_SHAPES = ${JSON.stringify(countries)};\nexport const CONTEXT_SHAPES = ${JSON.stringify(context)};\n`;
writeFileSync(out, js);
console.log('countries', Object.keys(countries).length, 'context', context.length, 'bytes', js.length, 'small', Object.entries(countries).filter(([, v]) => v.small).map(([k]) => k).join(','));
